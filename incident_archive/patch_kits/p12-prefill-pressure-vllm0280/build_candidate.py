from __future__ import annotations

import ast
import difflib
import hashlib
import json
from pathlib import Path
import subprocess


ROOT = Path(__file__).resolve().parent


def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def save_generated(target: Path, data: bytes) -> None:
    if target.exists():
        if target.read_bytes() != data:
            raise RuntimeError(f"refusing changed generated file: {target}")
        return
    if not data.endswith(b"\n"):
        raise RuntimeError(f"generated file lacks final newline: {target}")
    patch = f"*** Begin Patch\n*** Add File: {target}\n"
    patch += "".join("+" + line + "\n" for line in data.decode().splitlines())
    patch += "*** End Patch\n"
    subprocess.run(["apply_patch"], input=patch, text=True, check=True, capture_output=True)
    if target.read_bytes() != data:
        raise RuntimeError(f"generated bytes differ: {target}")


def replace_exact(text: str, old: str, new: str) -> str:
    if text.count(old) != 1 or new in text:
        raise RuntimeError(f"replacement is not unique: {old[:100]!r}")
    return text.replace(old, new, 1)


def runtime_payloads() -> tuple[dict[str, bytes], list[dict]]:
    module = ast.parse((ROOT / "sources/installer.py").read_text())
    changes = next(
        ast.literal_eval(node.value)
        for node in module.body
        if isinstance(node, ast.Assign)
        and any(isinstance(target, ast.Name) and target.id == "FILES" for target in node.targets)
    )
    payloads = {}
    adaptations = []
    for relative, (_, _, replacements) in changes.items():
        text = (ROOT / "sources/vllm-0.28.0/vllm" / relative).read_text()
        for position, (old, new) in enumerate(replacements, 1):
            if relative == "v1/core/sched/scheduler.py" and position == 1:
                prefix = "        self.defer_block_free = False\n"
                old = old.removeprefix(prefix)
                new = new.removeprefix(prefix)
                adaptations.append({"file": relative, "replacement": position, "reason": "preserve requires_kv_delivery initialization"})
            elif relative == "v1/core/sched/scheduler.py" and position == 2:
                old = "                if request.num_computed_tokens == 0:\n                    did_prefix_cache_lookup = True\n"
                new = old.replace(
                    "                    did_prefix_cache_lookup = True\n",
                    "                    request.prefill_cache_lookup_complete = False\n"
                    "                    request.prefill_cached_tokens = 0\n"
                    "                    did_prefix_cache_lookup = True\n",
                )
                adaptations.append({"file": relative, "replacement": position, "reason": "preserve did_prefix_cache_lookup and new local-hit implementation"})
            text = replace_exact(text, old, new)
        if relative == "v1/core/sched/scheduler.py":
            text = replace_exact(
                text,
                "        for request in self.requests.values():\n            if request.prefill_stats is None:\n",
                "        for request in self.requests.values():\n            if request.is_finished() or request.prefill_stats is None:\n",
            )
        ast.parse(text, filename=relative, feature_version=(3, 12))
        payloads["vllm/" + relative] = text.encode()
    return payloads, adaptations


def collector_payload() -> bytes:
    text = (ROOT / "sources/collectors/r106.py").read_text()
    for metric in ("miss_requests", "miss_tokens", "pending_requests"):
        old = (
            f'            "vllm:prefill_cache_{metric}",\n'
            "            args.ranks,\n"
            "            integer=True,\n"
            "            fill_missing_zero=True,\n"
        )
        text = replace_exact(text, old, old.replace("fill_missing_zero=True", "fill_missing_zero=False"))
    text = replace_exact(
        text,
        '    except Exception:\n        LOG.exception("Prefill metrics scrape failed")\n',
        '    except Exception:\n        miss_requests = miss_tokens = pending_requests = None\n        LOG.exception("Prefill metrics scrape failed")\n',
    )
    ast.parse(text, filename="static_dp_registrar.py", feature_version=(3, 12))
    return text.encode()


def build() -> dict:
    source_manifest = json.loads((ROOT / "source-manifest.json").read_text())
    for record in source_manifest["files"]:
        if digest((ROOT / record["path"]).read_bytes()) != record["sha256"]:
            raise RuntimeError(f"source checksum mismatch: {record['path']}")
    payloads, adaptations = runtime_payloads()
    records = []
    patch_lines = []
    for relative, payload in payloads.items():
        before = (ROOT / "sources/vllm-0.28.0" / relative).read_bytes()
        payload_path = "payload/" + relative
        save_generated(ROOT / payload_path, payload)
        records.append({"path": relative, "before_sha256": digest(before), "after_sha256": digest(payload), "payload": payload_path})
        patch_lines.extend(difflib.unified_diff(before.decode().splitlines(keepends=True), payload.decode().splitlines(keepends=True), fromfile="a/" + relative, tofile="b/" + relative))
    collector_before = (ROOT / "sources/collectors/r106.py").read_bytes()
    collector_after = collector_payload()
    collector_relative = "payload/static_dp_registrar.py"
    save_generated(ROOT / collector_relative, collector_after)
    collector_patch = "".join(difflib.unified_diff(collector_before.decode().splitlines(keepends=True), collector_after.decode().splitlines(keepends=True), fromfile="a/static_dp_registrar.py", tofile="b/static_dp_registrar.py"))
    manifest = {
        "candidate": "p12-prefill-pressure-vllm0280",
        "base_version": "0.28.0",
        "status": "offline_candidate_gpu_and_service_acceptance_pending",
        "required_components": ["vllm", "collector"],
        "runtime_files": records,
        "collector": {"before_sha256": digest(collector_before), "after_sha256": digest(collector_after), "payload": collector_relative, "identical_source_aliases": source_manifest["collector_identical_aliases"]},
        "v028_anchor_adaptations": adaptations,
        "fixes": ["exclude finished requests from pressure", "missing Prefill samples are unknown, not zero", "discard partial Prefill sample on parse failure"],
    }
    save_generated(ROOT / "v028-p12.patch", "".join(patch_lines).encode())
    save_generated(ROOT / "collector-p12.patch", collector_patch.encode())
    save_generated(ROOT / "manifest.json", (json.dumps(manifest, ensure_ascii=False, indent=2) + "\n").encode())
    return manifest


if __name__ == "__main__":
    result = build()
    print(json.dumps({"runtime_files": len(result["runtime_files"]), "collector_variants": result["collector"]["identical_source_aliases"]}))
